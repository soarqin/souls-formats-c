static void run_decrypt_against(const char *pem) {
    uint8_t *out = NULL;
    size_t   out_size = 0;
    sf_result_t r = sfi_rsa_decrypt_pkcs1(pem, k_test_ct, sizeof(k_test_ct),
                                          &out, &out_size, NULL);
    TEST_ASSERT_EQUAL_INT(SF_OK, r);
    TEST_ASSERT_NOT_NULL(out);

    size_t lead = 0;
    while (lead < sizeof(k_test_pt) && k_test_pt[lead] == 0x00u) lead++;
    size_t expected_len = sizeof(k_test_pt) - lead;
    TEST_ASSERT_EQUAL_size_t(expected_len, out_size);
    TEST_ASSERT_EQUAL_UINT8_ARRAY(k_test_pt + lead, out, expected_len);

    sf_free(NULL, out);
}

static void test_rsa_decrypt_pkcs1_pem(void) {
    run_decrypt_against(k_test_pem_pkcs1);
}

static void test_rsa_decrypt_x509_pem(void) {
    run_decrypt_against(k_test_pem_x509);
}

static void test_rsa_decrypt_invalid_args(void) {
    uint8_t *out = NULL;
    size_t out_size = 0;
    TEST_ASSERT_EQUAL_INT(SF_ERR_INVALID_ARG,
        sfi_rsa_decrypt_pkcs1(NULL, k_test_ct, sizeof(k_test_ct), &out, &out_size, NULL));
    TEST_ASSERT_EQUAL_INT(SF_ERR_INVALID_ARG,
        sfi_rsa_decrypt_pkcs1(k_test_pem_pkcs1, NULL, sizeof(k_test_ct), &out, &out_size, NULL));
    TEST_ASSERT_EQUAL_INT(SF_ERR_INVALID_ARG,
        sfi_rsa_decrypt_pkcs1(k_test_pem_pkcs1, k_test_ct, 0, &out, &out_size, NULL));
    TEST_ASSERT_EQUAL_INT(SF_ERR_INVALID_ARG,
        sfi_rsa_decrypt_pkcs1(k_test_pem_pkcs1, k_test_ct, sizeof(k_test_ct), NULL, &out_size, NULL));
}

