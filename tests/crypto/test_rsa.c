/* SPDX-License-Identifier: GPL-3.0-or-later
 *
 * Two sub-tests for sfi_rsa_decrypt_pkcs1:
 *
 *   1. Hermetic functional test using a throwaway 2048-bit keypair and a
 *      pre-computed (raw RSA, no padding) ciphertext. Test vectors were
 *      generated once with `openssl genrsa 2048` + `openssl pkeyutl
 *      -sign -pkeyopt rsa_padding_mode:none` and embedded directly in
 *      this file so the test has no runtime dependency on openssl, on
 *      Win32-vs-WSL temp paths, or on the network. The same plaintext
 *      is decoded once via the PKCS#1 PEM and once via the X.509 SPKI
 *      PEM to exercise both PEM-format paths.
 *
 *   2. Real-game smoke test using ELDEN RING's Data0.bhd if present at
 *      /mnt/c/Games/ELDEN RING/Game/Data0.bhd. SKIPs (returns PASS)
 *      when the file is absent so CI without a game install stays green.
 *      Verifies the recovered plaintext starts with 'B','H','D','5'.
 */

