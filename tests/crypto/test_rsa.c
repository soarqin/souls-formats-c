static void test_bhd5_keys_parse_round_trip(void) {
    for (int g = 0; g < (int)SF_BHD5_GAME_COUNT_; g++) {
        const char *pem = sfi_bhd5_get_pem_key((sf_bhd5_game_t)g);
        TEST_ASSERT_NOT_NULL(pem);
        uint8_t *out = NULL;
        size_t out_size = 0;
        sf_result_t r = sfi_rsa_decrypt_pkcs1(pem, k_test_ct, sizeof(k_test_ct),
                                              &out, &out_size, NULL);
        if (r == SF_OK) {
            sf_free(NULL, out);
        } else {
            TEST_ASSERT_EQUAL_INT(SF_ERR_CRYPTO, r);
        }
    }
}

static void test_rsa_real_eldenring_data0(void) {
    const char *path = "C:\\Games\\ELDEN RING\\Game\\Data0.bhd";
    sf_istream_t *s = NULL;
    if (sf_istream_open_file(&s, path, NULL) != SF_OK || !s) {
        TEST_PASS_MESSAGE("Skipped: ELDEN RING Data0.bhd not present");
        return;
    }
    uint8_t buf[256];
    sf_result_t r = sf_istream_read(s, buf, sizeof(buf));
    sf_istream_close(s);
    if (r != SF_OK) {
        TEST_PASS_MESSAGE("Skipped: ELDEN RING Data0.bhd unreadable");
        return;
    }

    const char *pem = sfi_bhd5_get_pem_key(SF_BHD5_GAME_ELDENRING);
    TEST_ASSERT_NOT_NULL(pem);

    uint8_t *out = NULL;
    size_t out_size = 0;
    r = sfi_rsa_decrypt_pkcs1(pem, buf, sizeof(buf), &out, &out_size, NULL);
    TEST_ASSERT_EQUAL_INT(SF_OK, r);
    TEST_ASSERT_NOT_NULL(out);
    TEST_ASSERT_GREATER_OR_EQUAL_size_t(4u, out_size);
    TEST_ASSERT_EQUAL_UINT8('B', out[0]);
    TEST_ASSERT_EQUAL_UINT8('H', out[1]);
    TEST_ASSERT_EQUAL_UINT8('D', out[2]);
    TEST_ASSERT_EQUAL_UINT8('5', out[3]);
    sf_free(NULL, out);
}

