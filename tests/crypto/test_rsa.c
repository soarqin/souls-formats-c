    TEST_ASSERT_NOT_NULL(sfi_bhd5_get_pem_key(SF_BHD5_GAME_ARMOREDCORE6));
    TEST_ASSERT_NULL(sfi_bhd5_get_pem_key(SF_BHD5_GAME_COUNT_));
    TEST_ASSERT_NULL(sfi_bhd5_get_pem_key((sf_bhd5_game_t)999));
