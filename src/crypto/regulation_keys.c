#include "crypto/regulation.h"
#include "internal/sf_internal.h"

static const uint8_t k_ds3[32] = {
    'd','s','3','#','j','n','/','8','_','7','(','r','s','Y','9','p',
    'g','5','5','G','F','N','7','V','F','L','#','+','3','n','/',')',
};
static const uint8_t k_er[32] = {
    0x99,0xBF,0xFC,0x36,0x6A,0x6B,0xC8,0xC6,0xF5,0x82,0x7D,0x09,0x36,0x02,0xD6,0x76,
    0xC4,0x28,0x92,0xA0,0x1C,0x20,0x7F,0xB0,0x24,0xD3,0xAF,0x4E,0x49,0x3F,0xEF,0x99,
};
static const uint8_t k_ac6[32] = {
    0x10,0xCE,0xED,0x47,0x7B,0x7C,0xD9,0xD7,0xE6,0x93,0x8E,0x11,0x47,0x13,0xE7,0x87,
    0xD5,0x39,0x13,0xB1,0x0D,0x31,0x8E,0xC1,0x35,0xE4,0xBE,0x50,0x50,0x4E,0x0E,0x10,
};
static const uint8_t k_nr[32] = {
    0x9A,0x8E,0xE9,0x0C,0x4C,0x01,0xA4,0x31,0x68,0xA1,0x7D,0x9D,0x75,0xE4,0xA7,0xD0,
    0x21,0x07,0xEB,0xCF,0x43,0xD5,0xAC,0xB0,0x55,0x4F,0x94,0x16,0x01,0xB5,0x79,0x18,
};

sf_result_t sfi_regulation_key(sf_regulation_key_t key, const uint8_t **out_key) {
    SF_CHECK_ARG(out_key);
    switch (key) {
    case SF_REGULATION_KEY_DARK_SOULS_3:           *out_key = k_ds3; return SF_OK;
    case SF_REGULATION_KEY_ELDEN_RING:             *out_key = k_er;  return SF_OK;
    case SF_REGULATION_KEY_ARMORED_CORE_6:         *out_key = k_ac6; return SF_OK;
    case SF_REGULATION_KEY_ELDEN_RING_NIGHTREIGN:  *out_key = k_nr;  return SF_OK;
    default:                                        return SF_ERR_INVALID_ARG;
    }
}
